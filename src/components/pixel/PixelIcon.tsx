// Computed once at module load; rendering only maps over these.
const icons = Object.fromEntries(
  Object.entries(sprites).map(([name, rows]) => [name, gridToRects(rows)]),
) as Record<PixelIconName, PixelRect[]>;

export function PixelIcon({ name, size, className, label }: PixelIconProps) {
  const rects = icons[name];
  const a11y = label ? { role: "img" as const, "aria-label": label } : { "aria-hidden": true as const };

  return (
    <svg
      viewBox="0 0 16 16"
      width={size}
      height={size}
      shapeRendering="crispEdges"
      fill="currentColor"
      className={className}
      focusable="false"
      {...a11y}
    >
      {rects.map((r, i) => (
        <rect
          key={i}
          x={r.x}
          y={r.y}
          width={r.w}
          height={r.h}
          fillOpacity={r.tone === "+" ? 0.5 : undefined}
        />
      ))}
    </svg>
  );
}
